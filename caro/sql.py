"""SQL for SQLite and for Postgres, written once.

Two stores keep rows in a database: the listings sellers post
(`webapp/api/store.py`) and the catalog of published runs
(`caro/catalog.py`). They are written in one SQL, the part the two databases
share. Where the databases differ -- the id column, how a parameter is
written, how a write transaction begins, how a new row's id comes back, what
keeps two processes from doing one thing at once -- is `DIALECTS`, here, and
nothing else in the project knows which database it has.

It is in `caro/` and not beside the seller store because the catalog is
read by more than the API: promotion writes it (docs/SERVICES.md, step 2),
and every service imports `caro`, never another service. A second copy of
this layer, one per store, is the two-copies-of-a-rule that SERVICES.md says
must not exist.

The driver for Postgres is imported only for a Postgres address, so the
suites and a laptop need nothing beyond Python. An error never quotes an
address: one can carry a password.
"""

from __future__ import annotations

import hashlib
import importlib
import re
import sqlite3
import time
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable, Iterable, Iterator

ROOT = Path(__file__).resolve().parent.parent


@dataclass(frozen=True)
class Dialect:
    name: str
    id_column: str          # an integer key the database assigns
    param: str              # how the driver wants a parameter written
    begin: str              # how a write transaction begins
    returning: bool         # whether a new id comes back by RETURNING
    migration_lock: str     # what keeps two processes from migrating at once
    key_lock: str           # the same, for one name, until the transaction ends


DIALECTS = {
    # BEGIN IMMEDIATE takes the write lock at once, so two writers queue
    # instead of failing halfway; it is also the migration's lock.
    "sqlite": Dialect("sqlite", "INTEGER PRIMARY KEY", "?", "BEGIN IMMEDIATE",
                      False, "", ""),
    "postgres": Dialect("postgres",
                        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                        "%s", "BEGIN", True,
                        "SELECT pg_advisory_xact_lock(2026103001)",
                        "SELECT pg_advisory_xact_lock(?)"),
}


def to_driver(sql: str, dialect: Dialect) -> str:
    """The SQL as the driver wants it: written with `?`, sent with the
    dialect's parameter. A `%` is refused rather than escaped: psycopg reads
    it as a parameter, and no statement here needs one -- a pattern is a
    parameter, never part of the SQL."""
    if "%" in sql:
        raise ValueError("a % in SQL; pass it as a parameter")
    return sql if dialect.param == "?" else sql.replace("?", dialect.param)


def sqlite_path(rest: str) -> str:
    """What follows `sqlite:///`: a path under the repository, an absolute
    path (a fourth slash), or `:memory:`."""
    if rest == ":memory:" or rest.startswith("/"):
        return rest
    return str(ROOT / rest)


def connect_sqlite(path: str) -> Any:
    conn = sqlite3.connect(path, isolation_level=None, timeout=10,
                           check_same_thread=False)
    # SQLite enforces a foreign key, and so the cascade, only when asked to,
    # on every connection.
    conn.execute("PRAGMA foreign_keys = ON")
    if path != ":memory:":
        conn.execute("PRAGMA journal_mode = WAL")
    return conn


def connect(url: str, *, setting: str, what: str,
            error: Callable[[str], Exception],
            importer: Callable[[str], Any] = importlib.import_module) -> tuple[Any, Dialect]:
    """(a connection in autocommit, its dialect) for `sqlite:///...` or
    `postgresql://...`. Anything else, a Postgres address without the
    driver, or one that refuses, raises `error`, naming `setting` -- the
    variable the address came from -- and never the address."""
    scheme, colon, _ = url.partition(":")
    if url.startswith("sqlite:///"):
        return connect_sqlite(sqlite_path(url[len("sqlite:///"):])), DIALECTS["sqlite"]
    if scheme.lower() in ("postgres", "postgresql"):
        try:
            psycopg = importer("psycopg")
        except ImportError as e:
            raise error(f"{setting} is a Postgres address and the driver, "
                        "psycopg, is not installed") from e
        try:
            conn = psycopg.connect(url, autocommit=True)
        except Exception as e:
            # the driver's message can quote the address; this one does not
            raise error(f"Postgres refused the connection ({type(e).__name__})") from None
        return conn, DIALECTS["postgres"]
    # the scheme alone, and only if it looks like one: a value with no
    # scheme at all could be anything, a password included
    named = (f"«{scheme.lower()}»" if colon and re.fullmatch(r"[A-Za-z][A-Za-z0-9+.-]{0,19}", scheme)
             else "none")
    raise error(f"{setting} is not an address {what} knows; its scheme: {named}")


class Database:
    """One connection, in autocommit, with transactions begun explicitly."""

    def __init__(self, conn: Any, dialect: Dialect,
                 clock: Callable[[], float] = time.time):
        self.conn = conn
        self.dialect = dialect
        self.clock = clock
        self._depth = 0

    # ---- statements --------------------------------------------------------
    def execute(self, sql: str, params: tuple = ()) -> Any:
        return self.conn.execute(to_driver(sql, self.dialect), params)

    def execute_many(self, sql: str, params: Iterable[tuple]) -> None:
        """One statement for many rows, in one round of the driver's."""
        cur = self.conn.cursor()
        try:
            cur.executemany(to_driver(sql, self.dialect), params)
        finally:
            cur.close()

    def rows(self, sql: str, params: tuple = ()) -> list[dict]:
        cur = self.execute(sql, params)
        names = [d[0] for d in cur.description or ()]
        return [dict(zip(names, r)) for r in cur.fetchall()]

    def row(self, sql: str, params: tuple = ()) -> dict | None:
        got = self.rows(sql, params)
        return got[0] if got else None

    def insert(self, sql: str, params: tuple = ()) -> int:
        """Runs an INSERT and gives the new row's id."""
        if self.dialect.returning:
            return int(self.execute(sql + " RETURNING id", params).fetchone()[0])
        return int(self.execute(sql, params).lastrowid)

    @contextmanager
    def transaction(self) -> Iterator[None]:
        """Everything inside is written, or none of it is. An inner one is
        part of the outer."""
        if self._depth:
            self._depth += 1
            try:
                yield
            finally:
                self._depth -= 1
            return
        self.execute(self.dialect.begin)
        self._depth = 1
        try:
            yield
        except BaseException:
            self._depth = 0
            self.execute("ROLLBACK")
            raise
        self._depth = 0
        self.execute("COMMIT")

    def now(self) -> int:
        return int(self.clock())

    def lock(self, name: str) -> None:
        """Holds `name` until the transaction ends, so two requests about the
        same thing take turns. SQLite needs nothing: BEGIN IMMEDIATE lets one
        writer in at a time."""
        if self.dialect.key_lock:
            n = int.from_bytes(hashlib.sha256(name.encode("utf-8")).digest()[:8], "big", signed=True)
            self.execute(self.dialect.key_lock, (n,))

    # ---- the schema --------------------------------------------------------
    def schema_version(self, table: str) -> int:
        """The last migration `table` records, or 0 where it does not exist."""
        try:
            r = self.row(f"SELECT MAX(version) AS v FROM {table}")
        except Exception:
            # no table yet. Postgres has aborted nothing: this ran outside a
            # transaction, in autocommit.
            return 0
        return int(r["v"] or 0) if r else 0

    def apply_migrations(self, migrations: tuple[tuple[int, tuple[str, ...]], ...], *,
                         table: str, lock: Callable[[], None]) -> list[int]:
        """Applies the migrations `table` does not record, in order, and gives
        their numbers. A second call applies nothing. Each runs in a
        transaction under `lock`, so two processes starting at once apply it
        once."""
        applied = []
        for number, statements in migrations:
            with self.transaction():
                lock()
                self.execute(f"CREATE TABLE IF NOT EXISTS {table} ("
                             "version INTEGER PRIMARY KEY, applied_at BIGINT NOT NULL)")
                if self.row(f"SELECT version FROM {table} WHERE version = ?", (number,)):
                    continue
                for s in statements:
                    self.execute(s.replace("{id}", self.dialect.id_column))
                self.execute(f"INSERT INTO {table} (version, applied_at) "
                             "VALUES (?, ?)", (number, self.now()))
                applied.append(number)
        return applied

    def close(self) -> None:
        self.conn.close()
